def search_and_click():
    search_text = search_entry_deal.get().lower()
    matching_buttons = []

    # Check for matching buttons and collect them
    for key, button in button_references.items():
        if search_text in key:
            matching_buttons.append(button)

    # Clear the existing layout
    for widget in scrollable_frame.winfo_children():
        widget.pack_forget()

    # Repack matching buttons first, then the rest
    for button in matching_buttons:
        button.pack(padx=55, pady=5, fill="x")
    for key, button in button_references.items():
        if button not in matching_buttons:
            button.pack(padx=55, pady=5, fill="x")

    if not matching_buttons:
        print(f"No match found for: {search_text}")


